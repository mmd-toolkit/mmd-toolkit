/**
 * Renders `src/rules/index.ts`, the list of the rules of the plugin, from the
 * rule files under `src/rules/`: a common rule in `src/rules/<name>.ts`, a
 * rule of a diagram type in `src/rules/<diagram>/<name>.ts`. Each rule file
 * exports one rule, named after the file in camel case (`noIgnoredText` in
 * `no-ignored-text.ts`). `update-rules.ts` writes the result, and
 * `tests/rules-index.test.ts` checks that the file holds it.
 */
import { readdirSync, statSync } from "node:fs"
import { fileURLToPath, pathToFileURL } from "node:url"
import { format, resolveConfig } from "prettier"

/** The directory of the rule files. */
const RULES_DIR: string = fileURLToPath(
  new URL("../src/rules/", import.meta.url),
)

/** The path of the generated list. */
export const RULES_INDEX_PATH: string = fileURLToPath(
  new URL("../src/rules/index.ts", import.meta.url),
)

/** A rule file: the rule's name in the plugin, and the name of its export. */
interface RuleFile {
  /** Such as `no-unclosed-directive` or `flowchart/no-ignored-text`. */
  readonly name: string
  /** The diagram of a rule of a diagram type, or null for a common rule. */
  readonly diagram: string | null
  /** The name that the file exports the rule under, such as `noIgnoredText`. */
  readonly exportName: string
}

/** `no-ignored-text` in camel case: `noIgnoredText`. */
function camelCase(kebabCase: string): string {
  return kebabCase
    .split("-")
    .map((word, index) =>
      index === 0 ? word : word.slice(0, 1).toUpperCase() + word.slice(1),
    )
    .join("")
}

/** The base names of the `.ts` files directly in `directory`, sorted. */
function ruleFileNames(directory: string): string[] {
  return readdirSync(directory)
    .filter((entry) => entry.endsWith(".ts") && entry !== "index.ts")
    .filter((entry) => statSync(`${directory}${entry}`).isFile())
    .map((entry) => entry.slice(0, -".ts".length))
    .sort()
}

/**
 * The rule files: the common rules, then the rules of each diagram type, each
 * sorted by name. Each file is imported to check that it exports one rule
 * under the name the convention gives it.
 */
async function ruleFiles(): Promise<RuleFile[]> {
  const files: RuleFile[] = ruleFileNames(RULES_DIR).map((base) => ({
    name: base,
    diagram: null,
    exportName: camelCase(base),
  }))
  const diagrams = readdirSync(RULES_DIR)
    .filter((entry) => statSync(`${RULES_DIR}${entry}`).isDirectory())
    .sort()
  for (const diagram of diagrams) {
    for (const base of ruleFileNames(`${RULES_DIR}${diagram}/`)) {
      files.push({
        name: `${diagram}/${base}`,
        diagram,
        exportName: camelCase(base),
      })
    }
  }
  for (const file of files) {
    const path = `${RULES_DIR}${file.name}.ts`
    const exports = Object.keys(
      (await import(pathToFileURL(path).href)) as object,
    )
    if (exports.length !== 1 || exports[0] !== file.exportName) {
      throw new Error(
        `${path} must export one rule, named ${file.exportName}; it exports ${exports.join(", ") || "nothing"}`,
      )
    }
  }
  return files
}

/**
 * The name a rule is imported under in the list: its export name, with the
 * diagram in front for a rule of a diagram type, since two diagram types may
 * have rules of the same name (`flowchartNoIgnoredText`).
 */
function importName(file: RuleFile): string {
  if (file.diagram === null) return file.exportName
  return (
    camelCase(file.diagram) +
    file.exportName.slice(0, 1).toUpperCase() +
    file.exportName.slice(1)
  )
}

/** The content of `src/rules/index.ts`, formatted. */
export async function renderRulesIndex(): Promise<string> {
  const files = await ruleFiles()
  const imports = files
    .map((file) => {
      const alias = importName(file)
      const binding =
        alias === file.exportName ? alias : `${file.exportName} as ${alias}`
      return {
        path: `./${file.name}.ts`,
        line: `import { ${binding} } from "./${file.name}.ts"`,
      }
    })
    .sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0))
    .map((entry) => entry.line)
  const lines = [
    "// This file is generated by tools/update-rules.ts from the rule files",
    "// under src/rules/: run `pnpm --filter eslint-plugin-mmd run update`.",
    'import type { ESLint } from "eslint"',
    ...imports,
    "",
    "/**",
    " * Every rule of the plugin, by its name in the plugin: a common rule by its",
    " * name, a rule of a diagram type by `<diagram>/<name>`. The rule id is the",
    " * name after the namespace, such as `mmd/flowchart/no-ignored-text`. The",
    " * document of a rule is `docs/rules/<name>.md`.",
    " */",
    'export const rules: NonNullable<ESLint.Plugin["rules"]> = {',
    ...files.map((file) => `  "${file.name}": ${importName(file)},`),
    "}",
    "",
  ]
  const options = await resolveConfig(RULES_INDEX_PATH)
  return format(lines.join("\n"), { ...options, filepath: RULES_INDEX_PATH })
}
